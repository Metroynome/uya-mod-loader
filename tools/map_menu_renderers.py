#!/usr/bin/env python3
"""Generate menu font addresses from exact/normalized function signatures.
Requires the user's RAC Levels extraction; ordinary builds use the checked-in table.
"""
import argparse,json,struct
from pathlib import Path

def fnv(data):
    h=2166136261
    for byte in data: h=((h^byte)*16777619)&0xffffffff
    return h

def generate(root,defs):
    reference=(root/'eemem/multiplayer/ntsc.39.Lobby.bin').read_bytes()
    width_sig=reference[0x590cf0:0x590cf0+64]
    print_sig=reference[0x590f90:0x590f90+48]
    set_sig=struct.unpack_from('<11I',reference,0x5908f8)
    masks=[0xffff0000 if w>>26 in (9,15) else 0xffffffff for w in set_sig]
    box_sig=struct.unpack_from('<16I',reference,0x615078)
    box_masks=[0xfc000000 if w>>26 in (2,3) else 0xffffffff for w in box_sig]
    context_deltas=[p-0x615078 for p in struct.unpack_from('<7I',reference,0x245e90)]
    output=['/* Generated by tools/map_menu_renderers.py; do not guess overlay offsets. */',
            'struct MenuRenderer { int level; unsigned int print, font, printHash, fontHash, box, boxHash, context, contextHash, width, widthHash; };']
    for region,number in [('ntscu',1),('pal',2),('ntscj',3)]:
        output.append(('#if' if number==1 else '#elif')+' UYA_MODULE_REGION == '+str(number))
        output.append('static const struct MenuRenderer renderers[] = {')
        count=0
        for level in defs['rac']['3']['levels']:
            if region not in level['region']: continue
            meta=level['region'][region];v=meta['defaultVersion'];info=meta['version'][v]
            code=info['code'].get('5')
            if not code: continue
            file=root/'code5'/('rac3.level%d.%s.v%s.%s.code.0005.bin'%(level['level'],region,v.replace('.',''),info['buildType']))
            data=file.read_bytes();pos=data.find(print_sig)
            if pos<0 or data.count(print_sig)!=1: raise ValueError('Ambiguous print signature: '+str(file))
            hits=[];start=0
            while True:
                i=data.find(struct.pack('<I',set_sig[0]),start)
                if i<0: break
                start=i+4
                if i%4 or i+44>len(data): continue
                words=struct.unpack_from('<11I',data,i)
                if all((a&m)==(b&m) for a,b,m in zip(words,set_sig,masks)): hits.append(i)
            if len(hits)!=1: raise ValueError('Ambiguous font signature: '+str(file))
            width=data.find(width_sig)
            if width<0 or data.count(width_sig)!=1: raise ValueError('Ambiguous width signature: '+str(file))
            base=int(code['offset'],16);font=hits[0]
            hits=[];start=0
            while True:
                p=data.find(struct.pack('<6I',*box_sig[:6]),start)
                if p<0: break
                start=p+4
                if p%4 or p+64>len(data): continue
                if all(a&m==b&m for a,b,m in zip(struct.unpack_from('<16I',data,p),box_sig,box_masks)):
                    hits.append(p)
            if len(hits)!=1: raise ValueError('Ambiguous box signature: '+str(file))
            box=hits[0]; box_address=base+box
            literal_file=root/'code0'/file.name.replace('0005.bin','0000.bin')
            literals=literal_file.read_bytes()
            context=struct.pack('<9I',0,0,*[box_address+d for d in context_deltas])
            offset=literals.find(context)
            if offset<0 or literals.count(context)!=1: raise ValueError('Ambiguous box context: '+str(file))
            context_address=int(info['code']['0']['offset'],16)+offset
            output.append('    {%d,0x%x,0x%x,0x%xU,0x%xU,0x%x,0x%xU,0x%x,0x%xU,0x%x,0x%xU},'%(
                level['level'],base+pos,base+font,fnv(data[pos:pos+48]),fnv(data[font:font+44]),
                box_address,fnv(data[box:box+64]),context_address,fnv(context),base+width,fnv(width_sig)))
            count+=1
        output.append('};');print(region,count,'verified overlay font pairs')
    output.append('#endif')
    return '\n'.join(output)+'\n'
if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('rac3',type=Path)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    text=generate(args.rac3,json.loads((args.rac3.parent/'rac-defs.json').read_text()))
    output=Path(__file__).resolve().parents[1]/'modules/modmenu/renderers.h'
    if args.check:
        assert output.read_text()==text, 'Renderer table is out of date'
    else: output.write_text(text)
